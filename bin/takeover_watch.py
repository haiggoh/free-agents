#!/usr/bin/env python3
"""takeover_watch.py — launchd WatchPaths agent for budget-wall spools (R4 plan Task 4, D5).

Installs com.haiggoh.free-agents.takeover-watch: launchd runs the runner shim whenever
<root>/.pending changes, so a spooled budget wall is captured (and auto-launched, when the
csl setting is ON) immediately instead of at the next SessionStart. The plist points at a
STABLE runner shim — no plugin-cache version, no checkout path anywhere in it; the shim
resolves the CURRENT installed plugin at run time (free-agents-resolve.sh semantics) and
execs its bin/budget-wall-capture.py --pending --from-watcher.

Usage: python3 takeover_watch.py [--help] {install|uninstall|status} [--dry-run]
Env: FA_TAKEOVER_DIR (state root; an invalid value aborts loudly), HOME, CLAUDE_PLUGIN_ROOT,
     FREE_AGENTS_PLUGIN. Exit codes: 0 ok, 2 usage.
"""
from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import fa_capture

LABEL = "com.haiggoh.free-agents.takeover-watch"
RUNNER_NAME = "takeover-watch-runner.sh"

# launchd's PATH is minimal (memory: path-differs) — set it explicitly in the plist.
PLIST_PATH_ENV = "/usr/bin:/bin:/usr/sbin:/sbin:/usr/local/bin:/opt/homebrew/bin"

RUNNER_TEMPLATE = """#!/usr/bin/env bash
# Generated by takeover_watch.py — stable path; resolves the CURRENT plugin at run time.
set -euo pipefail
cache="${CLAUDE_PLUGIN_ROOT:-$HOME/.claude/plugins/cache}/haiggoh/free-agents"
resolve=""
if [ -n "${FREE_AGENTS_PLUGIN:-}" ] && [ -f "$FREE_AGENTS_PLUGIN/bin/free-agents-resolve.sh" ]; then
  resolve="$FREE_AGENTS_PLUGIN/bin/free-agents-resolve.sh"
elif [ -d "$cache" ]; then
  resolve="$(ls -d "$cache"/*/bin/free-agents-resolve.sh 2>/dev/null | sort -V | tail -1)"
fi
if [ -z "$resolve" ]; then
  echo "takeover-watch-runner: no free-agents install found (cache=$cache)" >&2
  exit 1
fi
plugin="$(bash "$resolve")"
exec python3 "$plugin/bin/budget-wall-capture.py" --pending --from-watcher
"""


def _root() -> Path:
    return fa_capture.default_root()  # raises ValueError naming FA_TAKEOVER_DIR when invalid


def _home() -> Path:
    return Path(os.environ.get("HOME") or Path.home())


def _runner_path(root: Path) -> Path:
    return Path(root).parent / RUNNER_NAME  # stable: <state>/free-agents/takeover-watch-runner.sh


def _plist_path(home: Path) -> Path:
    return home / "Library" / "LaunchAgents" / f"{LABEL}.plist"


def render_plist(root: Path, runner: Path, home: Path) -> str:
    """XML plist text. A literal home path is allowed ONLY here: the generated plist is
    rendered from $HOME at install time. No cache version, no checkout path."""
    root = Path(root)
    return f"""<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>{LABEL}</string>
  <key>ProgramArguments</key>
  <array>
    <string>/bin/bash</string>
    <string>{runner}</string>
  </array>
  <key>WatchPaths</key>
  <array>
    <string>{root / ".pending"}</string>
  </array>
  <key>ThrottleInterval</key>
  <integer>10</integer>
  <key>RunAtLoad</key>
  <true/>
  <key>StandardOutPath</key>
  <string>{root / "watch.log"}</string>
  <key>StandardErrorPath</key>
  <string>{root / "watch.log"}</string>
  <key>EnvironmentVariables</key>
  <dict>
    <key>PATH</key>
    <string>{PLIST_PATH_ENV}</string>
  </dict>
</dict>
</plist>
"""


def _write_atomic(path: Path, data: str, mode: int) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    fd, tmp = tempfile.mkstemp(dir=str(path.parent), prefix=".tmp-")
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as f:
            f.write(data)
            f.flush()
            os.fsync(f.fileno())
        os.chmod(tmp, mode)
        os.replace(tmp, path)
    except BaseException:
        try:
            os.unlink(tmp)
        except OSError:
            pass
        raise


def status() -> dict:
    plist = _plist_path(_home())
    loaded = False
    try:
        out = subprocess.run(["launchctl", "list"], capture_output=True, text=True, timeout=10).stdout
        loaded = LABEL in out
    except Exception:
        loaded = False
    return {"installed": plist.is_file(), "loaded": loaded, "plist": str(plist)}


def install(dry_run: bool = False) -> int:
    root = _root()
    home = _home()
    runner = _runner_path(root)
    plist = _plist_path(home)
    xml = render_plist(root, runner, home)
    loaded = False if dry_run else status()["loaded"]  # dry-run: no launchctl call at all
    if dry_run:  # decided BEFORE any write or launchctl call
        print(f"would write runner {runner} (0755)")
        print(f"would write plist {plist} (0644)")
        print("already loaded — no bootstrap" if loaded
              else f"would run: launchctl bootstrap gui/{os.getuid()} {plist}")
        return 0
    _write_atomic(runner, RUNNER_TEMPLATE, 0o755)
    _write_atomic(plist, xml + "\n", 0o644)
    print(f"wrote runner {runner}")
    print(f"wrote plist {plist}")
    if not loaded:
        r = subprocess.run(["launchctl", "bootstrap", f"gui/{os.getuid()}", str(plist)],
                           capture_output=True, text=True)
        if r.returncode != 0:
            print(f"takeover_watch: launchctl bootstrap rc={r.returncode}: {r.stderr.strip()}",
                  file=sys.stderr)
        else:
            print(f"bootstrapped {LABEL}")
    else:
        print(f"{LABEL} already loaded — no bootstrap")
    return 0


def uninstall(dry_run: bool = False) -> int:
    root = _root()
    plist = _plist_path(_home())
    runner = _runner_path(root)
    if dry_run:  # decided BEFORE any write or launchctl call
        print(f"would run: launchctl bootout gui/{os.getuid()}/{LABEL}")
        print(f"would remove {plist}" + (f" and {runner}" if runner.exists() else ""))
        return 0
    subprocess.run(["launchctl", "bootout", f"gui/{os.getuid()}/{LABEL}"],
                   capture_output=True, text=True)  # rc ignored: not-loaded is the normal case
    removed = []
    for p in (plist, runner):
        try:
            p.unlink()
            removed.append(str(p))
        except FileNotFoundError:
            pass
    print("removed: " + (", ".join(removed) if removed else "nothing (already absent)"))
    return 0


def main(argv=None) -> int:
    p = argparse.ArgumentParser(
        prog="takeover_watch.py",
        description="Install/remove/status of the launchd WatchPaths agent that runs "
                    "budget-wall-capture.py --pending --from-watcher when <root>/.pending changes.",
        epilog="Env: FA_TAKEOVER_DIR (state root override; invalid aborts loudly), HOME, "
               "CLAUDE_PLUGIN_ROOT, FREE_AGENTS_PLUGIN. --dry-run writes nothing and calls no "
               "launchctl. Exit codes: 0 ok, 2 usage.")
    sub = p.add_subparsers(dest="cmd", required=True)
    for name in ("install", "uninstall"):
        s = sub.add_parser(name, help=f"{name} the LaunchAgent")
        s.add_argument("--dry-run", action="store_true", help="print what would change; write nothing")
    sub.add_parser("status", help="print installed/loaded/plist as JSON")
    args = p.parse_args(argv)
    try:
        if args.cmd == "install":
            return install(dry_run=args.dry_run)
        if args.cmd == "uninstall":
            return uninstall(dry_run=args.dry_run)
        print(json.dumps(status(), indent=2))
        return 0
    except ValueError as e:
        print(f"takeover_watch: {e}", file=sys.stderr)
        return 2


if __name__ == "__main__":
    raise SystemExit(main())
