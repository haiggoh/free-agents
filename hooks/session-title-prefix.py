#!/usr/bin/env python3
"""
UserPromptSubmit hook to set session title with launcher prefix + auto-generated name.

This hook runs after the first user prompt is submitted, and sets the session title
to: "<launcher-emoji> <model name> · <auto-generated-title>"

The model name is the readable one (LA_SESSION_TITLE_MODEL, e.g. "Z.ai GLM 5.3 (thinking)"),
not the provider-prefixed alias. Claude Code's own name is "<folder>-<id>"; in the HOME
folder the folder part is just the user name, so it is dropped (user 2026-10-22).

The auto-generated title is what Claude Code would normally assign based on the
conversation context. We read the current title (which will be the auto-generated
one after the first prompt) and prepend our prefix.

Environment variables (set by launchers):
- LA_SESSION_KIND_EMOJI: The emoji for the session kind (🦾, 📡, ☁️)
- LA_SESSION_TITLE_MODEL: The readable model name (remote sessions); preferred
- MODEL_ALIAS: The model alias (e.g., nvidia/nemotron-3-ultra-550b-a55b); the fallback
- LA_SESSION_IDENTITY: Full session identity JSON
"""

import json
import os
import sys
from pathlib import Path


def log(msg):
    """Log to stderr for debugging."""
    print(f"[session-title-prefix-hook] {msg}", file=sys.stderr)


SEP = " · "                      # between our prefix and Claude Code's own name
LAUNCHER_EMOJIS = ["🦾", "📡", "☁️", "❓"]


def get_prefix():
    """Get the session title prefix from environment: the launcher emoji and the readable
    model name (LA_SESSION_TITLE_MODEL), falling back to the alias for launchers that do not
    export one."""
    emoji = os.environ.get("LA_SESSION_KIND_EMOJI", "")
    model_alias = (os.environ.get("LA_SESSION_TITLE_MODEL", "")
                   or os.environ.get("MODEL_ALIAS", ""))
    if emoji and model_alias:
        return f"{emoji} {model_alias}"
    elif emoji:
        return emoji
    elif model_alias:
        return model_alias
    return ""


def strip_home_folder(name, cwd):
    """Claude Code names a session "<folder>-<id>". In the home folder there is no project, so
    the folder part is only the user name: keep the id, drop "<user>-"."""
    try:
        at_home = bool(cwd) and Path(cwd).resolve() == Path.home().resolve()
    except OSError:
        at_home = False
    lead = Path.home().name + "-"
    if at_home and name.startswith(lead) and len(name) > len(lead):
        return name[len(lead):]
    return name


def strip_launcher_prefix(name):
    """The auto-generated part of a name that already carries a launcher prefix, or None
    when it carries none. New titles separate the two with SEP (the model name has spaces);
    older ones were "<emoji> <one-word-alias> <auto>"."""
    for emoji in LAUNCHER_EMOJIS:
        if name.startswith(emoji + " "):
            if SEP in name:
                return name.split(SEP, 1)[1]
            parts = name.split(" ", 2)
            return parts[2] if len(parts) >= 3 else ""
    return None


def get_session_file(session_id):
    """Find the session metadata file for a session ID."""
    sessions_dir = Path.home() / ".claude" / "sessions"
    for session_file in sessions_dir.glob("*.json"):
        try:
            with open(session_file) as f:
                data = json.load(f)
                if data.get("sessionId") == session_id:
                    return session_file
        except Exception:
            continue
    return None


def print_help():
    """Print help message."""
    print("session-title-prefix.py - UserPromptSubmit hook to set session title with launcher prefix")
    print()
    print("Usage:")
    print("  python3 session-title-prefix.py")
    print()
    print("This hook runs after the first user prompt and sets the session title to:")
    print("  <emoji> <model name> · <auto-generated-title>")
    print("(in the home folder, Claude Code's '<user>-' part of the name is dropped)")
    print()
    print("Environment variables (set by launchers):")
    print("  LA_SESSION_KIND_EMOJI - Emoji for session kind (🦾, 📡, ☁️)")
    print("  LA_SESSION_TITLE_MODEL - Readable model name (preferred)")
    print("  MODEL_ALIAS           - Model alias (fallback when no readable name is set)")
    print("  LA_SESSION_IDENTITY   - Full session identity JSON")
    print()
    print("Input (stdin JSON):")
    print("  session_id - The Claude Code session ID")
    print("  cwd        - Current working directory")
    print()
    print("Output (stdout JSON):")
    print("  hookSpecificOutput.sessionTitle - The new session title")
    print()
    print("Exit codes:")
    print("  0 - Success (including skipped/idempotent)")
    print("  1 - Error")


def main():
    # Check for --help
    if len(sys.argv) > 1 and sys.argv[1] in ("-h", "--help"):
        print_help()
        return 0

    # Read hook input from stdin
    try:
        input_data = json.load(sys.stdin)
    except json.JSONDecodeError as e:
        log(f"Failed to parse stdin JSON: {e}")
        return 0

    # Get session ID
    session_id = input_data.get("session_id", "")
    if not session_id:
        log("No session_id in hook input")
        return 0
    
    # Get the prefix
    prefix = get_prefix()
    if not prefix:
        log("No prefix configured (missing LA_SESSION_KIND_EMOJI or MODEL_ALIAS)")
        return 0
    
    # Get the current session file
    session_file = get_session_file(session_id)
    if not session_file:
        log(f"Could not find session file for ID: {session_id}")
        return 0
    
    # Read current session name
    try:
        with open(session_file) as f:
            session_data = json.load(f)
    except Exception as e:
        log(f"Error reading session file: {e}")
        return 0
    
    current_name = session_data.get("name", "")

    # Already carrying the EXACT current prefix: nothing to do (idempotent)
    if current_name.startswith(prefix + SEP) or current_name == prefix:
        log("Prefix already applied, skipping")
        return 0

    # A DIFFERENT launcher prefix (another model on resume, or the older format): replace it,
    # keeping only Claude Code's own part
    auto = strip_launcher_prefix(current_name)
    if auto is not None:
        log(f"Replacing existing launcher prefix with current: {prefix}")
        current_name = auto
    current_name = strip_home_folder(current_name, input_data.get("cwd", ""))

    new_name = f"{prefix}{SEP}{current_name}" if current_name else prefix
    
    # Return hookSpecificOutput to set the session title
    # This is the mechanism from the changelog: UserPromptSubmit hooks can set sessionTitle
    output = {
        "hookSpecificOutput": {
            "hookEventName": "UserPromptSubmit",
            "sessionTitle": new_name
        }
    }
    
    print(json.dumps(output))
    log(f"Set session title to: {new_name}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
